#!/usr/bin/env python3
"""Generate src/core/unicode_data.inc: Unicode general-category ranges and the White_Space set."""
import sys, unicodedata

CATS = ["Lu", "Ll", "Lt", "Lm", "Lo", "Mn", "Mc", "Me", "Nd", "Nl", "No", "Pc", "Pd", "Ps", "Pe", "Pi", "Pf", "Po",
        "Sm", "Sc", "Sk", "So", "Zs", "Zl", "Zp", "Cc", "Cf", "Cs", "Co", "Cn"]
WHITE = [0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x20, 0x85, 0xA0, 0x1680] + list(range(0x2000, 0x200B)) + [0x2028, 0x2029, 0x202F, 0x205F, 0x3000]

def main(out):
    ranges, start, prev = [], 0, unicodedata.category(chr(0))
    for cp in range(1, 0x110000):
        c = unicodedata.category(chr(cp))
        if c != prev:
            ranges.append((start, cp - 1, prev)); start, prev = cp, c
    ranges.append((start, 0x10FFFF, prev))
    with open(out, "w") as f:
        f.write(f"// Generated by scripts/gen_unicode.py from Unicode {unicodedata.unidata_version}. Do not edit.\n")
        f.write("// {first, last, category} with category indexing k_cat_names.\n")
        f.write("static const char *const k_cat_names[] = {" + ", ".join(f'"{c}"' for c in CATS) + "};\n")
        f.write("static const struct { uint32_t first, last; uint8_t cat; } k_cat_ranges[] = {\n")
        for a, b, c in ranges:
            if c != "Cn":
                f.write(f"{{0x{a:X},0x{b:X},{CATS.index(c)}}},\n")
        f.write("};\nstatic const uint32_t k_white_space[] = {" + ", ".join(f"0x{c:X}" for c in WHITE) + "};\n")

if __name__ == "__main__":
    main(sys.argv[1])
